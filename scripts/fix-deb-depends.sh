#!/usr/bin/env bash
# Repair the `.deb` dependency list emitted by tauri-cli.
#
# `tauri-cli` appends four dependencies of its own to whatever the config says
# (see `interface/rust.rs`): libayatana-appindicator3-1, libappindicator3-1,
# libwebkit2gtk-4.1-0 and libgtk-3-0. The last one is unsatisfiable on Ubuntu
# 24.04+ and Debian 13, where the 64-bit time_t transition renamed the package
# to libgtk-3-0t64. Because the name is pushed after the configured list, it
# cannot be removed from `tauri.conf.json`; the bundled control file has to be
# rewritten. Doing it here keeps the release artifact installable instead of
# shipping one that `dpkg -i` refuses.
#
# The rewrite is conservative: it only removes an exact `libgtk-3-0` entry when
# an alternative clause covers it, deduplicates entries, and leaves every other
# dependency untouched.
set -euo pipefail

if [[ $# -ne 1 || ! -f "$1" ]]; then
  echo "usage: $0 path/to/package.deb" >&2
  exit 2
fi

deb=$1
case $deb in
  *.deb) ;;
  *) echo "not a .deb: $deb" >&2; exit 2 ;;
esac

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

dpkg-deb -R "$deb" "$work/root"

python3 - "$work/root/DEBIAN/control" <<'PY'
import sys

path = sys.argv[1]
lines = open(path, encoding="utf-8").read().splitlines()
out = []
repaired = False

for line in lines:
    if not line.startswith("Depends:"):
        out.append(line)
        continue

    deps = [d.strip() for d in line[len("Depends:"):].split(",") if d.strip()]
    alternatives = [d for d in deps if "|" in d]
    covered = any("libgtk-3-0" in alt for alt in alternatives)
    # Drop the bare pre-t64 name only when an alternative clause still requires
    # a GTK 3 library; otherwise leave the list exactly as the bundler wrote it.
    kept = [d for d in deps if not (covered and d == "libgtk-3-0")]

    seen = set()
    deduped = []
    for dep in kept:
        if dep not in seen:
            seen.add(dep)
            deduped.append(dep)

    if covered and not any("libgtk-3-0" in dep for dep in deduped):
        deduped.append("libgtk-3-0 | libgtk-3-0t64")

    out.append("Depends: " + ", ".join(deduped))
    repaired = True

if not repaired:
    sys.exit("no Depends line in control; refusing to guess")

open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
PY

# Rebuild in place. `--root-owner-group` keeps the archive root-owned like the
# bundler's output; the md5sums are regenerated by dpkg-deb.
rebuilt="$work/rebuilt.deb"
dpkg-deb --build --root-owner-group "$work/root" "$rebuilt" >/dev/null
mv "$rebuilt" "$deb"

echo "repaired: $(dpkg-deb -f "$deb" Depends)"
